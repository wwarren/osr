#!/usr/bin/env python3
"""Check install-target.sh against Project Maya's real code at the pinned commit.

Usage: python3 test-pinned-run-script.py /path/to/fetched/project-maya
The checkout must have fetched the pinned commit into FETCH_HEAD. No model,
Python packages, GPU, or server process is needed: the launcher generator and
updater run in isolation, with updater network and Git actions forbidden.

What it pins down, because install-target.sh, the monitor and the router rely
on it:
  - the launcher setup writes, and the exact "start script:" line it prints,
    which install-target.sh's select_run_script must accept;
  - the setup options install-target.sh passes (--draft, --nvcc, --host, ...);
  - --yes --no-start setups write the launcher and are not held up by tuning;
  - MAYA_UPDATE_CHECK=0 (set in maya.service) keeps the dashboard from
    updating the checkout behind the installer;
  - /v1/models lists no model while the engine is down (the monitor treats
    that as down).
"""

import ast
import os
from pathlib import Path
import shlex
import subprocess
import sys
import tempfile
from types import SimpleNamespace
from unittest.mock import Mock, patch


PIN = "a4e1ff087a4097a73713336df5912d03a1453c46"   # v1.1.15
HERE = Path(__file__).resolve().parent


def git(repo, *args):
    return subprocess.check_output(
        ["git", "-c", f"safe.directory={repo}", "-C", str(repo), *args],
        text=True,
    ).strip()


def function(tree, name):
    return next(node for node in tree.body
                if isinstance(node, ast.FunctionDef) and node.name == name)


def select_run_script(log_line, maya_dir):
    """Run install-target.sh's own select_run_script on one setup log line."""
    helpers = subprocess.check_output(
        ["awk", "/^# Install helpers/{c=1;next} /^# End install helpers\\./{c=0} c",
         str(HERE / "install-target.sh")], text=True)
    with tempfile.NamedTemporaryFile("w", suffix=".log", delete=False) as log:
        log.write(log_line + "\n")
    try:
        return subprocess.run(
            ["bash", "-c", helpers + '\nselect_run_script "$1" && printf "%s" "$run_script"',
             "test", log.name],
            env={"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "MAYA_DIR": str(maya_dir)},
            capture_output=True, text=True)
    finally:
        os.unlink(log.name)


def check_update_switch(source, repo):
    """Exercise the upstream updater with network and Git forbidden."""
    namespace = {"__file__": str(repo / "serve" / "update.py"),
                 "__name__": "pinned_maya_update"}
    exec(compile(source, "pinned update.py", "exec"), namespace)
    updater_type = namespace["Updater"]
    forbidden = Mock(side_effect=AssertionError("disabled updater attempted an external action"))
    with patch.dict(os.environ, {"MAYA_UPDATE_CHECK": "0"}), \
            patch.object(namespace["urllib"].request, "urlopen", forbidden), \
            patch.object(namespace["subprocess"], "run", forbidden), \
            patch.object(namespace["threading"], "Thread", forbidden), \
            patch.object(namespace["os"], "_exit", forbidden), \
            patch.dict(namespace, {"git": forbidden}):
        updater = updater_type("1.0.0", root=repo)
        updater._fetch_latest = forbidden
        info = updater.check(force=True)
        assert not info["enabled"] and not info["can_update"] and not info["newer"], info
        try:
            updater.start(SimpleNamespace())
        except ValueError:
            pass
        else:
            raise AssertionError("disabled updater accepted an update")
        assert updater.thread is None
        forbidden.assert_not_called()
    # Control case: the same check must actually run when the switch is on.
    with patch.dict(os.environ, {"MAYA_UPDATE_CHECK": "1"}):
        updater = updater_type("1.0.0", root=repo)
        updater._fetch_latest = Mock()
        updater.check(force=True)
        updater._fetch_latest.assert_called_once_with()


def main():
    if len(sys.argv) != 2:
        raise SystemExit("Usage: test-pinned-run-script.py /path/to/fetched/project-maya")
    repo = Path(sys.argv[1]).resolve()
    actual = git(repo, "rev-parse", "FETCH_HEAD")
    assert actual == PIN, f"expected Maya {PIN}, got {actual}"
    maya = git(repo, "show", "FETCH_HEAD:maya.py")
    setup = git(repo, "show", "FETCH_HEAD:setup.py")
    update = git(repo, "show", "FETCH_HEAD:serve/update.py")
    server = git(repo, "show", "FETCH_HEAD:serve/server.py")

    # 1. The launcher, generated by upstream's own function.
    tree = ast.parse(maya)
    generator = function(tree, "write_run_script")
    with tempfile.TemporaryDirectory(prefix="maya-launcher-") as temporary:
        root = Path(temporary)
        namespace = {
            "ROOT": root, "HERE": root, "WIN": False, "shlex": shlex, "Path": Path,
            "ME": "./maya.sh", "cmdline": lambda cmd: " ".join(cmd),
            "sys": SimpleNamespace(executable="/opt/maya/.venv/bin/python"),
        }
        exec(compile(ast.Module(body=[generator], type_ignores=[]), "pinned maya.py", "exec"),
             namespace)
        cfg = root / "maya-maya-s-v2-iq2_xxs.json"
        script = namespace["write_run_script"](cfg, 8080)
        assert script == root / "run-maya-maya-s-v2-iq2_xxs.sh", script
        assert script.stat().st_mode & 0o111, "launcher is not executable"
        lines = script.read_text(encoding="utf-8").splitlines()
        assert lines[0] == "#!/bin/sh"
        assert lines[-1].startswith("exec /opt/maya/.venv/bin/python ") and \
            f"--config {cfg} --port 8080" in lines[-1], lines[-1]

        # 2. The line setup prints for it, through setup.py's ok() format,
        #    must be what select_run_script picks.
        assert 'say(f"  [ok] {msg}")' in setup, "setup.py ok() format changed"
        assert 'ok(f"start script: {write_run_script(cfg_path, port)}")' in maya, \
            "maya.py no longer prints the start script path this way"
        result = select_run_script(f"  [ok] start script: {script}", root)
        assert result.returncode == 0 and result.stdout == str(script), result.stderr
        result = select_run_script(f"  [ok] start script: /elsewhere/{script.name}", root)
        assert result.returncode != 0 and "outside" in result.stderr, result

    # 3. The options install-target.sh passes or checks exist.
    for flag in ("--setup", "--no-start", "--yes", "--plain", "--download-model", "--model",
                 "--draft", "--no-vision", "--models-dir", "--context", "--port", "--host",
                 "--api-key", "--nvcc"):
        assert f'ap.add_argument("{flag}"' in maya, f"maya.py has no {flag}"
    assert 'DRAFTS = ("mtp", "dflash2")' in maya

    # 4. A --yes --no-start setup writes the launcher and is not held up.
    written = maya.index("cfg_path = write_config(")
    assert maya.index("not a.yes and\n             not a.no_start)", written) > written
    assert maya.index("if cfg_path is None or a.no_start:", written) > written

    # 5. The update switch maya.service relies on.
    check_update_switch(update, repo)
    service = (HERE / "maya.service").read_text(encoding="utf-8")
    assert "\nEnvironment=MAYA_UPDATE_CHECK=0\n" in service

    # 6. /v1/models is empty while the engine is down.
    assert '"data": [model] if loaded else []' in server

    print(f"PASS Maya {PIN}: launcher line, setup options, update switch and model list match")


if __name__ == "__main__":
    main()
